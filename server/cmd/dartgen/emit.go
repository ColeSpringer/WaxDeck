package main

import (
	"fmt"
	"maps"
	"path"
	"path/filepath"
	"slices"
	"sort"
	"strings"
	"unicode/utf8"
)

const header = "// Generated by dartgen from the API spec and its hints; do not edit.\n"

// Files the emitted code imports, relative to -out; the hand-written
// ones live in the package beside the output directory.
const (
	enumsFile      = "enums.g.dart"
	barrelFile     = "models.g.dart"
	codecFile      = "codec.g.dart"
	handModelsFile = "../hand_models.dart"
	modelsFile     = "../models.dart"
	wireFile       = "../wire.dart"
)

func modelFile(stem string) string { return "models/" + stem + ".g.dart" }

// dartFile is one emitted file under construction.
type dartFile struct {
	path    string                     // relative to -out, slash-separated
	imports map[string]map[string]bool // uri -> names shown, none for all
	exports []dartExport
	decls   []string
	// viaBarrel imports generated classes and enums through the model
	// barrel rather than their own files.
	viaBarrel bool
}

type dartExport struct {
	uri  string
	show []string // none for all
}

func newDartFile(p string) *dartFile {
	return &dartFile{path: p, imports: map[string]map[string]bool{}}
}

// use imports target (relative to -out, or a dart: library), showing
// only show when given.
func (f *dartFile) use(target string, show ...string) {
	uri := target
	if !strings.HasPrefix(target, "dart:") {
		uri = relativeURI(path.Dir(f.path), target)
		if uri == path.Base(f.path) {
			return
		}
	}
	names, ok := f.imports[uri]
	if !ok {
		names = map[string]bool{}
		f.imports[uri] = names
	}
	for _, n := range show {
		names[n] = true
	}
}

func relativeURI(fromDir, target string) string {
	rel, err := filepath.Rel(filepath.FromSlash(path.Join("out", fromDir)), filepath.FromSlash(path.Join("out", target)))
	if err != nil {
		panic(err)
	}
	return filepath.ToSlash(rel)
}

func (f *dartFile) bytes() []byte {
	var b strings.Builder
	b.WriteString(header)
	var sdk, local []string
	for uri := range f.imports {
		if strings.HasPrefix(uri, "dart:") {
			sdk = append(sdk, uri)
		} else {
			local = append(local, uri)
		}
	}
	sort.Strings(sdk)
	sort.Strings(local)
	for _, group := range [][]string{sdk, local} {
		if len(group) == 0 {
			continue
		}
		b.WriteString("\n")
		for _, uri := range group {
			fmt.Fprintf(&b, "import '%s'", uri)
			if show := slices.Sorted(maps.Keys(f.imports[uri])); len(show) > 0 {
				fmt.Fprintf(&b, " show %s", strings.Join(show, ", "))
			}
			b.WriteString(";\n")
		}
	}
	if len(f.exports) > 0 {
		b.WriteString("\n")
		for _, e := range f.exports {
			fmt.Fprintf(&b, "export '%s'", e.uri)
			if len(e.show) > 0 {
				fmt.Fprintf(&b, " show %s", strings.Join(e.show, ", "))
			}
			b.WriteString(";\n")
		}
	}
	for _, d := range f.decls {
		b.WriteString("\n")
		b.WriteString(d)
	}
	return []byte(b.String())
}

// useType imports what naming t takes in f.
func (f *dartFile) useType(t *dartType) {
	switch t.kind {
	case kBytes:
		f.use("dart:typed_data")
	case kAPIError:
		f.use(modelsFile, "WaxDeckApiException")
	case kClass:
		f.useClass(t.class)
	case kEnum:
		if f.viaBarrel {
			f.use(barrelFile)
		} else {
			f.use(enumsFile)
		}
	case kList, kMap:
		f.useType(t.elem)
	}
}

func (f *dartFile) useClass(c *class) {
	switch {
	case c.hand:
		f.use(handModelsFile)
	case f.viaBarrel:
		f.use(barrelFile)
	default:
		f.use(modelFile(c.file))
	}
}

// docLines reflows text into /// lines that fit 80 columns at indent,
// keeping its paragraphs.
func docLines(text, indent string) []string {
	width := 80 - len(indent) - len("/// ")
	var out []string
	for i, para := range paragraphs(text) {
		if i > 0 {
			out = append(out, indent+"///")
		}
		line := ""
		for _, word := range docWords(para) {
			switch {
			case line == "":
				line = word
			case utf8.RuneCountInString(line)+1+utf8.RuneCountInString(word) > width:
				out = append(out, indent+"/// "+line)
				line = word
			default:
				line += " " + word
			}
		}
		out = append(out, indent+"/// "+line)
	}
	return out
}

// docWords is para's words with each code span kept as one, so a reflow
// never breaks a line inside one: the analyzer reads each doc line on its
// own, and a <tag> wrapped out of its span reads as HTML. With unbalanced
// backticks it is the plain words.
func docWords(para string) []string {
	var out []string
	open := false
	for _, w := range strings.Fields(para) {
		if open {
			out[len(out)-1] += " " + w
		} else {
			out = append(out, w)
		}
		if strings.Count(w, "`")%2 == 1 {
			open = !open
		}
	}
	if open {
		return strings.Fields(para)
	}
	return out
}

func paragraphs(text string) []string {
	var out, cur []string
	for _, line := range strings.Split(text, "\n") {
		if strings.TrimSpace(line) == "" {
			if len(cur) > 0 {
				out = append(out, strings.Join(cur, " "))
				cur = nil
			}
			continue
		}
		cur = append(cur, line)
	}
	if len(cur) > 0 {
		out = append(out, strings.Join(cur, " "))
	}
	return out
}

func writeLines(b *strings.Builder, lines []string) {
	for _, l := range lines {
		b.WriteString(l)
		b.WriteString("\n")
	}
}

// emit builds every model-side file of the run, keyed by path relative to
// -out; pub is what a public signature reaches.
func (m *model) emit(pub publicSet) map[string][]byte {
	out := map[string][]byte{}
	byFile := map[string][]*class{}
	for _, c := range m.generated() {
		byFile[c.file] = append(byFile[c.file], c)
	}
	barrel := newDartFile(barrelFile)
	barrel.exports = append(barrel.exports, dartExport{uri: enumsFile})
	for _, stem := range slices.Sorted(maps.Keys(byFile)) {
		f := newDartFile(modelFile(stem))
		for _, c := range byFile[stem] {
			f.decls = append(f.decls, classDecl(f, c))
			if pages(c) {
				f.decls = append(f.decls, pagingDecl(c))
			}
		}
		out[f.path] = f.bytes()
		barrel.exports = append(barrel.exports, dartExport{uri: f.path})
	}
	enums := newDartFile(enumsFile)
	for _, e := range m.sortedEnums() {
		enums.decls = append(enums.decls, enumDecl(e))
	}
	out[enums.path] = enums.bytes()
	out[barrel.path] = barrel.bytes()
	public := pub.barrel(m)
	out[public.path] = public.bytes()
	codec := m.codec()
	if internal := pub.internal(m); len(internal) > 0 {
		codec.exports = append(codec.exports, dartExport{uri: barrelFile, show: internal})
	}
	out[codecFile] = codec.bytes()
	return out
}

const urlDoc = "Arrives resolved against the client's base URL."

func classDecl(f *dartFile, c *class) string {
	var b strings.Builder
	writeLines(&b, docLines(c.doc, ""))
	extends := ""
	if c.base != nil {
		extends = " extends " + c.base.name
		f.useClass(c.base)
	}
	fmt.Fprintf(&b, "class %s%s {\n", c.name, extends)
	if params := c.params(); len(params) == 0 {
		fmt.Fprintf(&b, "  const %s();\n", c.name)
	} else {
		fmt.Fprintf(&b, "  const %s({\n", c.name)
		for _, p := range params {
			fmt.Fprintf(&b, "    %s,\n", param(c, p))
		}
		b.WriteString("  });\n")
	}
	for _, fl := range c.fields {
		b.WriteString("\n")
		doc := docLines(fl.doc, "  ")
		if fl.typ.url {
			doc = append(doc, "  /// "+urlDoc)
		}
		writeLines(&b, doc)
		fmt.Fprintf(&b, "  final %s %s;\n", fl.dart(), fl.name)
		f.useType(fl.typ)
	}
	b.WriteString("}\n")
	return b.String()
}

// pagingDecl is the extension giving c, which pages, its hasMore.
func pagingDecl(c *class) string {
	cursor := cursorField(c).name
	return fmt.Sprintf("/// Keyset paging over [%s].\nextension %s on %s {\n"+
		"  /// Whether [%s] names a next page.\n  bool get %s => %s != null;\n}\n",
		c.name, pagingExtension(c), c.name, cursor, pagingMember, cursor)
}

// param is p as a parameter of c's constructor: a super parameter when a
// base declares it, keeping the base's required-ness and default. A
// default makes even a required property's parameter optional.
func param(c *class, p *field) string {
	if p.owner != c {
		if p.required && p.def == "" {
			return "required super." + p.name
		}
		return "super." + p.name
	}
	switch {
	case p.def != "":
		return "this." + p.name + " = " + p.def
	case p.required:
		return "required this." + p.name
	}
	return "this." + p.name
}

func enumDecl(e *enumDef) string {
	var b strings.Builder
	writeLines(&b, docLines(e.doc, ""))
	fmt.Fprintf(&b, "enum %s {\n", e.name)
	for i, member := range e.members {
		end := ","
		if i == len(e.members)-1 {
			end = ";"
		}
		fmt.Fprintf(&b, "  %s(%s)%s\n", member, dartString(e.values[i]), end)
	}
	fmt.Fprintf(&b, "\n  const %s(this.wireName);\n\n", e.name)
	b.WriteString("  /// The value as the wire spells it.\n  final String wireName;\n\n")
	// fromWire's parameter, wire, hides a member of that name.
	fallback := e.fallback
	if fallback == "wire" {
		fallback = e.name + "." + fallback
	}
	switch {
	case e.fallback != "":
		fmt.Fprintf(&b, "  /// The member [wire] spells; any other spelling reads as [%s].\n", fallback)
	case e.drop:
		b.WriteString("  /// The member [wire] spells, or null for one this build does not know,\n" +
			"  /// which drops the object holding it from its list.\n")
	default:
		b.WriteString("  /// The member [wire] spells, or null for one this build does not know.\n")
	}
	fmt.Fprintf(&b, "  static %s? fromWire(String? wire) {\n", e.name)
	if e.fallback != "" {
		b.WriteString("    if (wire == null) return null;\n")
	}
	b.WriteString("    for (final value in values) {\n      if (value.wireName == wire) return value;\n    }\n")
	if e.fallback != "" {
		fmt.Fprintf(&b, "    return %s;\n", fallback)
	} else {
		b.WriteString("    return null;\n")
	}
	b.WriteString("  }\n}\n")
	return b.String()
}
