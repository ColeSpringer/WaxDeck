// A plain download's date is the day it was published where it came from,
// so accept-best judges it without the year; a release date its Art Track
// description supplied still counts.
func TestAcceptBestJudgesADownloadWithoutItsUploadDate(t *testing.T) {
	t.Parallel()
	h, src := acceptBestHarness(t, obviousRelease()...)
	acquire := func(name, desc string) ReviewEntryDetail {
		t.Helper()
		paths, err := fixtures.Generate(t.TempDir(), fixtures.Spec{
			Name: name, Codec: fixtures.CodecMP3, Duration: 3 * time.Second,
			Tags: map[string]string{"TITLE": "Quiet Wire", "ARTIST": "Hold Steady State", "DATE": "2016"},
		})
		if err != nil {
			t.Fatal(err)
		}
		url := "https://tube.example/watch?v=" + name
		src.files[url] = paths[0]
		if desc != "" {
			src.descriptions = map[string]string{url: desc}
		}
		task := decodeStatus[ToolTask](t, postJSONAs(t, h, h.token, "/api/v1/acquisitions",
			map[string]any{"url": url, "mediaType": "music", "acceptBestMatch": true}), 202, "acquisition")
		drainTools(t, h)
		drainMatches(t, h)
		got := decode[ToolTask](t, get(t, h.ts, "/api/v1/tools/tasks/"+task.Id, h.token))
		if got.State != "done" || got.ResultPids == nil || len(*got.ResultPids) != 1 {
			t.Fatalf("acquire task = %+v", got)
		}
		return getReview(t, h, (*got.ResultPids)[0])
	}

	late := acquire("late", "")
	if late.Status != "auto-applied" || late.AppliedMbid == nil || *late.AppliedMbid != "rel-obvious" {
		t.Fatalf("download dated five years on = %s applied %v withheld %q, want auto-applied rel-obvious",
			late.Status, late.AppliedMbid, withheld(late))
	}

	described := acquire("described", "Provided to YouTube by Wire Label\n\nQuiet Wire · Hold Steady State\n\nQuiet Wire\n\n"+
		"℗ 2016 Wire Label\n\nReleased on: 2016-05-01\n\nAuto-generated by YouTube.")
	if described.Status != "pending" || withheld(described) != "below-floor" {
		t.Fatalf("Art Track released five years off = %s withheld %q, want pending below-floor",
			described.Status, withheld(described))
	}
}

// A download judged on the artist and title its title splits into can find
// its best past the candidates the tags as read rank first: that best is
// stored with them, so it can be applied.
func TestAcceptBestAppliesABestPastTheStoredCandidates(t *testing.T) {
	t.Parallel()
	releases := obviousRelease()
	for i := range 5 {
		releases = append(releases, &match.Release{
			MBID: fmt.Sprintf("rel-decoy-%d", i), ReleaseGroupMBID: fmt.Sprintf("rg-decoy-%d", i),
			Title: fmt.Sprintf("Decoy %d", i), Artist: "Hold Steady State", Year: 2021, Media: 1,
			Tracks: []match.ReleaseTrack{{
				RecordingMBID: fmt.Sprintf("00000000-0000-4000-8000-0000000000d%d", i),
				Title:         "Hold Steady State Quiet Wire", Position: 1, DurationSec: 3,
			}},
		})
	}
	h, src := acceptBestHarness(t, releases...)
	e := acquireVideo(t, h, src, "past", "Hold Steady State", "Hold Steady State - Quiet Wire", map[string]any{"acceptBestMatch": true})
	if e.Status != "auto-applied" || e.AppliedMbid == nil || *e.AppliedMbid != "rel-obvious" {
		t.Fatalf("entry = %s applied %v withheld %q with %d candidates, want auto-applied rel-obvious",
			e.Status, e.AppliedMbid, withheld(e), len(e.Candidates))
	}
	if len(e.Candidates) != 6 {
		t.Fatalf("stored %d candidates, want the five as read and the best past them", len(e.Candidates))
	}

	// Not asked, the entry stores the five alone.
	quiet := acquireVideo(t, h, src, "quiet", "Hold Steady State", "Hold Steady State - Quiet Wire", nil)
	if len(quiet.Candidates) != 5 {
		t.Fatalf("an entry that did not ask stored %d candidates, want 5", len(quiet.Candidates))
	}
}
