package sourcenoise

import (
	"reflect"
	"strings"
	"testing"
)

// Descriptions written from the layout YouTube auto-generates for Art Track
// uploads. U+00B7 separates the title from its artists; U+2117 and U+00A9 open
// the phonographic and plain copyright lines.
const (
	artTrackOneArtist = "Provided to YouTube by Universal Music Group\n" +
		"\n" +
		"Bohemian Rhapsody \u00b7 Queen\n" +
		"\n" +
		"A Night At The Opera\n" +
		"\n" +
		"\u2117 2011 Hollywood Records\n" +
		"\n" +
		"Released on: 1975-11-21\n" +
		"\n" +
		"Producer: Roy Thomas Baker\n" +
		"Composer  Lyricist: Freddie Mercury\n" +
		"\n" +
		"Auto-generated by YouTube."

	artTrackSeveralArtists = "Provided to YouTube by Sony Music Entertainment\n" +
		"\n" +
		"Under Pressure \u00b7 Queen \u00b7 David Bowie\n" +
		"\n" +
		"Hot Space\n" +
		"\n" +
		"\u2117 1982 Queen Productions Ltd\n" +
		"\n" +
		"Released on: 1982-05-21\n" +
		"\n" +
		"Auto-generated by YouTube."

	artTrackNoReleased = "Provided to YouTube by DistroKid\n" +
		"\n" +
		"Night Drive \u00b7 Small Artist\n" +
		"\n" +
		"Night Drive\n" +
		"\n" +
		"\u2117 Small Artist\n" +
		"\n" +
		"Auto-generated by YouTube."

	artTrackExtraLines = "Provided to YouTube by Warner Records\n" +
		"\n" +
		"Song Title (feat. Guest) \u00b7 Main Artist \u00b7 Guest\n" +
		"\n" +
		"The Album (Deluxe Edition)\n" +
		"\n" +
		"\u2117 2020 Warner Records Inc.\n" +
		"\u00a9 2020 Warner Records Inc.\n" +
		"\n" +
		"Released on: 2020-02-29\n" +
		"\n" +
		"Associated  Performer, Vocals: Main Artist\n" +
		"Studio  Personnel, Mixing  Engineer: Someone Else\n" +
		"Music  Publisher: Some Publishing\n" +
		"\n" +
		"Auto-generated by YouTube.\n"

	artTrackRealCredits = "Provided to YouTube by EMI\n" +
		"\n" +
		"Bohemian Rhapsody \u00b7 Queen\n" +
		"\n" +
		"A Night At The Opera (2011 Remaster)\n" +
		"\n" +
		"\u2117 2011 Queen Productions Ltd, under exclusive licence to Universal International Music BV\n" +
		"\n" +
		"Released on: 1975-10-31\n" +
		"\n" +
		"Composer, Lyricist: Freddie Mercury\n" +
		"Studio  Personnel, Mixing  Engineer: Mike Stone\n" +
		"Associated  Performer, Vocals (Backing): Roger Taylor\n" +
		"Producer (2011 Remaster): Bob Ludwig\n" +
		"\n" +
		"Auto-generated by YouTube."

	artTrackMinimal = "Provided to YouTube by Label\n" +
		"\n" +
		"Track \u00b7 Artist\n" +
		"\n" +
		"Album"
)

func TestParseArtTrackDescription(t *testing.T) {
	cases := []struct {
		name string
		desc string
		want ArtTrack
		ok   bool
	}{
		{
			name: "one artist",
			desc: artTrackOneArtist,
			want: ArtTrack{Title: "Bohemian Rhapsody", Artists: []string{"Queen"}, Album: "A Night At The Opera", Released: "1975-11-21"},
			ok:   true,
		},
		{
			name: "several artists",
			desc: artTrackSeveralArtists,
			want: ArtTrack{Title: "Under Pressure", Artists: []string{"Queen", "David Bowie"}, Album: "Hot Space", Released: "1982-05-21"},
			ok:   true,
		},
		{
			name: "no released line",
			desc: artTrackNoReleased,
			want: ArtTrack{Title: "Night Drive", Artists: []string{"Small Artist"}, Album: "Night Drive"},
			ok:   true,
		},
		{
			name: "extra copyright and credit lines",
			desc: artTrackExtraLines,
			want: ArtTrack{Title: "Song Title (feat. Guest)", Artists: []string{"Main Artist", "Guest"}, Album: "The Album (Deluxe Edition)", Released: "2020-02-29"},
			ok:   true,
		},
		{
			name: "windows line ends",
			desc: strings.ReplaceAll(artTrackSeveralArtists, "\n", "\r\n"),
			want: ArtTrack{Title: "Under Pressure", Artists: []string{"Queen", "David Bowie"}, Album: "Hot Space", Released: "1982-05-21"},
			ok:   true,
		},
		{
			name: "leading blank lines",
			desc: "\n\n" + artTrackMinimal,
			want: ArtTrack{Title: "Track", Artists: []string{"Artist"}, Album: "Album"},
			ok:   true,
		},
		{
			name: "the three required blocks alone",
			desc: artTrackMinimal,
			want: ArtTrack{Title: "Track", Artists: []string{"Artist"}, Album: "Album"},
			ok:   true,
		},
		{
			name: "an invalid release date parses without it",
			desc: strings.Replace(artTrackSeveralArtists, "1982-05-21", "1982-02-30", 1),
			want: ArtTrack{Title: "Under Pressure", Artists: []string{"Queen", "David Bowie"}, Album: "Hot Space"},
			ok:   true,
		},
		{
			name: "a year-only release date parses without it",
			desc: strings.Replace(artTrackSeveralArtists, "1982-05-21", "1982", 1),
			want: ArtTrack{Title: "Under Pressure", Artists: []string{"Queen", "David Bowie"}, Album: "Hot Space"},
			ok:   true,
		},
		{
			name: "real credit lines with commas, parentheses and doubled spaces",
			desc: artTrackRealCredits,
			want: ArtTrack{Title: "Bohemian Rhapsody", Artists: []string{"Queen"}, Album: "A Night At The Opera (2011 Remaster)", Released: "1975-10-31"},
			ok:   true,
		},
		{
			name: "free text after the album is read past",
			desc: artTrackMinimal + "\n\nThanks for listening! Subscribe for more.\n\nReleased on: 2020-01-02",
			want: ArtTrack{Title: "Track", Artists: []string{"Artist"}, Album: "Album", Released: "2020-01-02"},
			ok:   true,
		},
		{
			name: "a link after the album is read past",
			desc: artTrackMinimal + "\n\nhttps://example.invalid/merch",
			want: ArtTrack{Title: "Track", Artists: []string{"Artist"}, Album: "Album"},
			ok:   true,
		},

		{
			name: "an album titled with a colon",
			desc: strings.Replace(artTrackOneArtist, "A Night At The Opera", "Hamilton: An American Musical", 1),
			want: ArtTrack{Title: "Bohemian Rhapsody", Artists: []string{"Queen"}, Album: "Hamilton: An American Musical", Released: "1975-11-21"},
			ok:   true,
		},
		{
			name: "an album titled as a role and a name",
			desc: strings.Replace(artTrackMinimal, "\n\nAlbum", "\n\nBlack Panther: The Album", 1),
			want: ArtTrack{Title: "Track", Artists: []string{"Artist"}, Album: "Black Panther: The Album"},
			ok:   true,
		},
		{
			name: "a short album titled with a colon",
			desc: strings.Replace(artTrackMinimal, "\n\nAlbum", "\n\nRe: Stacks", 1),
			want: ArtTrack{Title: "Track", Artists: []string{"Artist"}, Album: "Re: Stacks"},
			ok:   true,
		},

		// Shapes that must not parse.
		{name: "empty", desc: ""},
		{name: "blank", desc: "\n \n"},
		{
			name: "hand-written description",
			desc: "Official video for Bohemian Rhapsody \u00b7 Queen\n\nStream it everywhere: https://example.invalid\n\nFollow us on socials",
		},
		{
			name: "provided line not first",
			desc: "Our new single!\n\n" + artTrackMinimal,
		},
		{
			name: "provided line with no label",
			desc: strings.Replace(artTrackMinimal, "Provided to YouTube by Label", "Provided to YouTube by", 1),
		},
		{
			name: "missing album block",
			desc: "Provided to YouTube by Label\n\nTrack \u00b7 Artist\n\n\u2117 2020 Label\n\nReleased on: 2020-01-01\n\nAuto-generated by YouTube.",
		},
		{
			name: "only the provided and title blocks",
			desc: "Provided to YouTube by Label\n\nTrack \u00b7 Artist",
		},
		{
			name: "title line with no artist",
			desc: "Provided to YouTube by Label\n\nTrack\n\nAlbum\n\nAuto-generated by YouTube.",
		},
		{
			name: "title line with an empty artist",
			desc: "Provided to YouTube by Label\n\nTrack \u00b7 \n\nAlbum",
		},
		{
			name: "middot without spaces is not the separator",
			desc: "Provided to YouTube by Label\n\nTrack\u00b7Artist\n\nAlbum",
		},
		{
			name: "title block with a second line",
			desc: "Provided to YouTube by Label\n\nTrack \u00b7 Artist\nMore text\n\nAlbum",
		},
		{
			name: "album block with a second line",
			desc: "Provided to YouTube by Label\n\nTrack \u00b7 Artist\n\nAlbum\nCheck out our merch\n\nAuto-generated by YouTube.",
		},
		{
			name: "provided block with a second line",
			desc: "Provided to YouTube by Label\nTrack \u00b7 Artist\n\nAlbum",
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, ok := ParseArtTrackDescription(c.desc)
			if ok != c.ok {
				t.Fatalf("ok = %v, want %v (got %+v)", ok, c.ok, got)
			}
			if !ok {
				if !reflect.DeepEqual(got, ArtTrack{}) {
					t.Fatalf("a refused description returned %+v", got)
				}
				return
			}
			if !reflect.DeepEqual(got, c.want) {
				t.Fatalf("got %+v, want %+v", got, c.want)
			}
		})
	}
}
